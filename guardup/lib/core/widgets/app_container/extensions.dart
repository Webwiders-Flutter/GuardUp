import 'package:flutter/material.dart';
import 'app_container_shape.dart';
import 'app_container_widget.dart';

extension QuickContainerExtension on Widget {
  /// Wraps this widget in a [QuickContainer].
  ///
  /// Mirrors the [QuickContainer] constructor — see its docs for details.
  AppContainer quick({
    double? w,
    double? h,
    double? minW,
    double? minH,
    double? maxW,
    double? maxH,
    double? p,
    double? px,
    double? py,
    double? pt,
    double? pb,
    double? pl,
    double? pr,
    double? m,
    double? mx,
    double? my,
    double? mt,
    double? mb,
    double? ml,
    double? mr,
    Color? color,
    Gradient? gradient,
    DecorationImage? image,
    BlendMode? blendMode,
    AppContainerShape shape = AppContainerShape.rectangle,
    double? radius,
    double? radiusTL,
    double? radiusTR,
    double? radiusBL,
    double? radiusBR,
    BorderRadius? borderRadius,
    BoxBorder? border,
    Color? borderColor,
    double? borderWidth,
    bool dashed = false,
    double dashLength = 8.0,
    double gapLength = 5.0,
    bool dotted = false,
    double dotWidth = 3.0,
    double? dotHeight,
    double dotSpacing = 5.0,
    bool shadow = false,
    List<BoxShadow>? shadows,
    VoidCallback? onTap,
    VoidCallback? onLongPress,
    bool ripple = false,
    bool disabled = false,
    bool animated = false,
    Duration duration = const Duration(milliseconds: 300),
    Curve curve = Curves.easeInOut,
    AlignmentGeometry? alignment,
    Clip clipBehavior = Clip.antiAlias,
    bool safeArea = false,
    bool loading = false,
  }) {
    return AppContainer(
      w: w,
      h: h,
      minW: minW,
      minH: minH,
      maxW: maxW,
      maxH: maxH,
      p: p,
      px: px,
      py: py,
      pt: pt,
      pb: pb,
      pl: pl,
      pr: pr,
      m: m,
      mx: mx,
      my: my,
      mt: mt,
      mb: mb,
      ml: ml,
      mr: mr,
      color: color,
      gradient: gradient,
      image: image,
      blendMode: blendMode,
      shape: shape,
      radius: radius,
      radiusTL: radiusTL,
      radiusTR: radiusTR,
      radiusBL: radiusBL,
      radiusBR: radiusBR,
      borderRadius: borderRadius,
      border: border,
      borderColor: borderColor,
      borderWidth: borderWidth,
      dashed: dashed,
      dashLength: dashLength,
      gapLength: gapLength,
      dotted: dotted,
      dotWidth: dotWidth,
      dotHeight: dotHeight,
      dotSpacing: dotSpacing,
      shadow: shadow,
      shadows: shadows,
      onTap: onTap,
      onLongPress: onLongPress,
      ripple: ripple,
      disabled: disabled,
      animated: animated,
      duration: duration,
      curve: curve,
      alignment: alignment,
      clipBehavior: clipBehavior,
      safeArea: safeArea,
      loading: loading,
      child: this,
    );
  }
}
